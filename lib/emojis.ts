export function searchEmojiCategories(query: string) {
  const normalizedQuery = query.trim().toLocaleLowerCase("ru-RU");
  if (!normalizedQuery) return emojiCategories;

  return emojiCategories
    .map((category) => {
      const categoryMatches = `${category.label} ${category.keywords || ""}`
        .toLocaleLowerCase("ru-RU")
        .includes(normalizedQuery);
      const emojiMatches = category.emojis.filter((emoji) => emoji.includes(normalizedQuery));
      return categoryMatches ? category : { ...category, emojis: emojiMatches };
    })
    .filter((category) => category.emojis.length > 0);
}
