function createGeneratedQuizzes() {
  return generatedMeta.flatMap(([slug, titlePrefix, description], categoryIndex) =>
    generatedThemesByCategory[categoryIndex].map<Quiz>((theme, quizIndex) => {
      const questionCount = 10 + (quizIndex % 11);
      const isAgree = categoryIndex === 5;
      const isWas = categoryIndex === 6;
      const isPhoto = categoryIndex === 7;
      const questions = Array.from({ length: questionCount }, (_, questionIndex) => {
        const template = generatedQuestionTemplates[questionIndex % generatedQuestionTemplates.length];
        const id = `${slug}-${quizIndex + 1}-${questionIndex + 1}`;
        const text = `${template.replace("{theme}", theme)} [${categoryIndex + 1}.${quizIndex + 1}.${questionIndex + 1}]`;

        if (isPhoto) {
          return { id, text, answerType: "photo" as const };
        }

        return {
          id,
          text,
          options: isAgree ? agreeOptions : isWas ? wasOptions : generatedChoiceOptions,
        };
      });

      return {
        id: `${slug}-${quizIndex + 1}`,
        category: quizCategories[categoryIndex],
        title: `${titlePrefix}: ${theme}`,
        description,
        duration: `${questionCount} ${isPhoto ? "фото" : "вопросов"}`,
        questions,
      };
    })
  );
}

export const quizzes: Quiz[] = [...baseQuizzes, ...createGeneratedQuizzes()];

export function getQuizById(quizId: string | null) {
  return quizzes.find((quiz) => quiz.id === quizId) || null;
}
